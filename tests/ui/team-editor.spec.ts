import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { gameStatisticsWorld } from './game-statistics-fixture';

test('tap swap, toast undo, kit colours, publish, coin start and active recolor keep team identities', async ({ page }) => {
  await page.setViewportSize({ width:390,height:844 });
  const world=gameStatisticsWorld({count:2});
  await world.attach(page); await page.goto('/event/7?tab=teams');
  await mkdir('artifacts/team-editor',{recursive:true});
  const red=page.getByRole('group',{name:'Красные',exact:true});
  const blue=page.getByRole('group',{name:'Синие',exact:true});
  await expect(page.getByRole('region',{name:'Баланс команд'})).toContainText('Разница средних');
  await expect(page.getByRole('button',{name:'Начать матч',exact:true})).toBeVisible();
  await page.screenshot({path:'artifacts/team-editor/editor-dark-390.png',fullPage:true});
  await red.getByRole('button',{name:'Али',exact:true}).click();
  const pick=page.getByRole('region',{name:'Обмен игроков'});
  await expect(pick).toContainText('Обмен: Али');
  await page.screenshot({path:'artifacts/team-editor/swap-dark-390.png'});
  await blue.getByRole('button',{name:'Баур',exact:true}).click();
  await expect(blue.getByRole('button',{name:'Али',exact:true})).toBeVisible();
  await page.locator('.toast').getByRole('button',{name:'Отменить',exact:true}).click();
  await expect(red.getByRole('button',{name:'Али',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Изменить цвет: Красные',exact:true}).click();
  const colors=page.getByRole('dialog',{name:'Форма: Красные'});
  await expect(colors.getByRole('button',{name:'Красный, сейчас',exact:true})).toHaveAttribute('aria-pressed','true');
  await colors.getByRole('button',{name:'Синий, у Синих',exact:true}).click();
  await expect(page.getByRole('button',{name:'Начать матч',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Опубликовать составы',exact:true}).click();
  await expect(page.getByRole('button',{name:'Начать матч',exact:true})).toBeVisible();
  expect(world.colors).toEqual(['blue','red']);
  await page.getByRole('button',{name:'Начать матч',exact:true}).click();
  const start=page.getByRole('dialog',{name:'Начинаем матч'});
  await expect(start.getByText('Кто начинает с мячом?')).toBeVisible();
  await start.getByRole('button',{name:'Подбросить монету',exact:true}).click();
  await expect(start.getByText(/^С мячом начинают /)).toBeVisible();
  await page.screenshot({path:'artifacts/team-editor/coin-dark-390.png'});
  await start.getByRole('button',{name:'К игре 1',exact:true}).click();
  await expect(page).toHaveURL(/tab=games/);
  await page.getByRole('tab',{name:'Составы',exact:true}).click();
  await expect(page.getByRole('region',{name:'Баланс команд'})).toHaveCount(0);
  await page.getByRole('button',{name:'Изменить цвет: Синие',exact:true}).first().click();
  await page.getByRole('dialog',{name:'Форма: Синие'}).getByRole('button',{name:'Зелёный',exact:true}).click();
  await expect(page.getByRole('group',{name:'Зелёные',exact:true}).getByRole('button',{name:'Али',exact:true})).toBeVisible();
  const revision=world.revision;
  await page.getByRole('tab',{name:'Игры',exact:true}).click();
  await expect(page.locator('.game-current')).toContainText('Зелёные');
  expect(world.revision).toBe(revision);
  expect(world.games).toHaveLength(0);
});

test('failed publication retains the edited draft and retries without a false conflict', async ({page}) => {
  const world=gameStatisticsWorld({count:2});world.failNextPublish=true;
  await world.attach(page);await page.goto('/event/7?tab=teams');
  await page.getByRole('button',{name:'Али',exact:true}).click();
  await page.getByRole('button',{name:'Баур',exact:true}).click();
  await page.getByRole('button',{name:'Опубликовать составы',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Твой вариант сохранён');
  await expect(page.getByRole('button',{name:'Начать матч',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Опубликовать составы',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Опубликовать составы',exact:true}).click();
  await expect(page.getByRole('button',{name:'Начать матч',exact:true})).toBeVisible();
  expect(world.detail().teams.teams[1]).toContain(1);
});

