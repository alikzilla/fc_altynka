import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { gameStatisticsWorld } from './game-statistics-fixture';

test('swap, toast undo, uniform colors, publish and active recolor keep team identities', async ({ page }) => {
  await page.setViewportSize({ width:390,height:844 });
  const world=gameStatisticsWorld({count:2});
  await world.attach(page); await page.goto('/event/7?tab=teams');
  await mkdir('artifacts/team-editor',{recursive:true});
  await expect(page.getByRole('button',{name:'Обменять: Али',exact:true})).toBeVisible();
  const firstSwap=await page.getByRole('button',{name:'Обменять: Али',exact:true}).boundingBox();
  const bottomAction=await page.getByRole('region',{name:'Действие матча',exact:true}).boundingBox();
  expect(firstSwap!.y+firstSwap!.height).toBeLessThan(bottomAction!.y);
  await page.screenshot({path:'artifacts/team-editor/editor-dark-390.png',fullPage:true});
  await page.getByRole('button',{name:'Обменять: Али',exact:true}).click();
  const swap=page.getByRole('dialog',{name:'Обменять игрока'});
  await expect.poll(()=>swap.evaluate(el=>Math.abs(el.getBoundingClientRect().bottom-innerHeight))).toBeLessThan(2);
  await page.screenshot({path:'artifacts/team-editor/swap-dark-390.png'});
  await expect(swap.getByRole('button',{name:/Перевести/})).toHaveCount(0);
  await swap.getByRole('button',{name:'Обменять с игроком Баур',exact:true}).click();
  await expect(page.getByRole('group',{name:'Синие',exact:true}).getByRole('button',{name:'Али',exact:true})).toBeVisible();
  await page.locator('.toast').getByRole('button',{name:'Отменить',exact:true}).click();
  await expect(page.getByRole('group',{name:'Красные',exact:true}).getByRole('button',{name:'Али',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Цвета команд',exact:true}).click();
  let colors=page.getByRole('dialog',{name:'Форма и манишки'});
  await colors.getByRole('button',{name:'Синий цвет для команды 1',exact:true}).click();
  await expect(colors.getByRole('button',{name:'Красный цвет для команды 2',exact:true})).toHaveAttribute('aria-pressed','true');
  await colors.getByRole('button',{name:'Применить цвета',exact:true}).click();
  await expect(page.getByRole('button',{name:'Начать встречу',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Опубликовать составы',exact:true}).click();
  await expect(page.getByRole('button',{name:'Начать встречу',exact:true})).toBeVisible();
  expect(world.colors).toEqual(['blue','red']);
  await page.getByRole('button',{name:'Начать встречу',exact:true}).click();
  await page.getByRole('dialog',{name:'Начать встречу?'}).getByRole('button',{name:'Начать встречу',exact:true}).click();
  await expect(page).toHaveURL(/tab=games/);
  await page.getByRole('tab',{name:'Составы',exact:true}).click();
  await expect(page.getByRole('button',{name:/Обменять:/})).toHaveCount(0);
  await page.getByRole('button',{name:'Цвета команд',exact:true}).click();
  colors=page.getByRole('dialog',{name:'Форма и манишки'});
  await colors.getByRole('button',{name:'Зелёный цвет для команды 1',exact:true}).click();
  await colors.getByRole('button',{name:'Применить цвета',exact:true}).click();
  await expect(page.getByRole('group',{name:'Зелёные',exact:true}).getByRole('button',{name:'Али',exact:true})).toBeVisible();
  const revision=world.revision;
  await page.getByRole('tab',{name:'Игра',exact:true}).click();
  await expect(page.locator('.game-current')).toContainText('Зелёные');
  expect(world.revision).toBe(revision);
  expect(world.games).toHaveLength(0);
});

test('failed publication retains the edited draft and retries without a false conflict', async ({page}) => {
  const world=gameStatisticsWorld({count:2});world.failNextPublish=true;
  await world.attach(page);await page.goto('/event/7?tab=teams');
  await page.getByRole('button',{name:'Обменять: Али',exact:true}).click();
  await page.getByRole('button',{name:'Обменять с игроком Баур',exact:true}).click();
  await page.getByRole('button',{name:'Опубликовать составы',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Твой вариант сохранён');
  await expect(page.getByRole('button',{name:'Начать встречу',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Опубликовать составы',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Опубликовать составы',exact:true}).click();
  await expect(page.getByRole('button',{name:'Начать встречу',exact:true})).toBeVisible();
  expect(world.detail().teams.teams[1]).toContain(1);
});

